def get_attr(message, name):
    for value in (a.value for a in message.attributes if a.key == name):
        return getattr(value, value.WhichOneof("value"))
    return None


def attempt_events(span):
    return [e for e in span.events if e.name == "nginx.upstream.attempt"]


def split_spans(spans):
    servers = [s for s in spans if s.kind == trace_pb2.Span.SPAN_KIND_SERVER]
    clients = [s for s in spans if s.kind == trace_pb2.Span.SPAN_KIND_CLIENT]
    return servers, clients


def assert_basic_parentage(spans, backend_name):
    servers, clients = split_spans(spans)
    assert len(clients) == 1
    assert len(servers) == 2
    outgoing = clients[0]
    backend = next(s for s in servers if s.name == backend_name)
    frontend = next(s for s in servers if s is not backend)
    assert outgoing.trace_id == frontend.trace_id == backend.trace_id
    assert outgoing.parent_span_id == frontend.span_id
    assert backend.parent_span_id == outgoing.span_id
    return frontend, outgoing, backend


